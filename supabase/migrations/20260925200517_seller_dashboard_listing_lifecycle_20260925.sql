create or replace function private.guard_seller_product_lifecycle()
returns trigger
language plpgsql
security definer
set search_path = public, private, pg_catalog
as $function$
begin
  if (select private.is_admin()) or current_user = 'service_role' then
    return new;
  end if;

  if auth.uid() is not null and old.owner_id = auth.uid() then
    if (
      new.owner_id is distinct from old.owner_id
      or new.status is distinct from old.status
      or new.moderation_status is distinct from old.moderation_status
    )
    and coalesce(current_setting('deba.lifecycle_override', true), '') <> '1' then
      raise exception 'SELLER_PRODUCT_LIFECYCLE_USE_RPC';
    end if;
  end if;

  return new;
end;
$function$;

drop trigger if exists trg_guard_seller_product_lifecycle on public.products;

create trigger trg_guard_seller_product_lifecycle
before update of owner_id, status, moderation_status
on public.products
for each row
execute function private.guard_seller_product_lifecycle();

drop policy if exists products_insert_seller on public.products;
create policy products_insert_seller
on public.products
for insert
to authenticated
with check (
  (select private.is_admin())
  or (
    owner_id = (select auth.uid())
    and exists (
      select 1
      from public.profiles p
      where p.id = (select auth.uid())
        and p.account_type = 'seller'
    )
    and status = 'draft'
    and moderation_status = 'pending'
  )
);

drop policy if exists products_delete_seller on public.products;
create policy products_delete_seller
on public.products
for delete
to authenticated
using (
  (select private.is_admin())
  or (
    owner_id = (select auth.uid())
    and exists (
      select 1
      from public.profiles p
      where p.id = (select auth.uid())
        and p.account_type = 'seller'
    )
    and status = 'draft'
    and moderation_status in ('pending', 'rejected', 'needs_changes')
    and not exists (
      select 1 from public.orders o where o.product_id = products.id
    )
    and not exists (
      select 1 from public.offers o where o.product_id = products.id
    )
  )
);

create or replace function private.get_seller_dashboard(
  p_seller_id uuid
)
returns table (
  id uuid,
  title text,
  slug text,
  price numeric,
  currency text,
  quantity integer,
  status text,
  moderation_status text,
  condition_grade text,
  created_at timestamptz,
  updated_at timestamptz,
  published_at timestamptz,
  sold_at timestamptz,
  image_storage_path text,
  views_count bigint,
  offers_count bigint,
  active_chats_count bigint
)
language plpgsql
stable
security definer
set search_path = public, pg_catalog
as $function$
begin
  if p_seller_id is null or p_seller_id <> auth.uid() then
    raise exception 'Authenticated seller is required' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.profiles p
    where p.id = p_seller_id
      and p.account_type = 'seller'
  ) then
    raise exception 'Seller account is required' using errcode = '42501';
  end if;

  return query
  select
    p.id,
    p.title,
    p.slug,
    p.price,
    p.currency,
    p.quantity,
    p.status,
    p.moderation_status,
    p.condition_grade,
    p.created_at,
    p.updated_at,
    p.published_at,
    p.sold_at,
    (
      select pi.storage_path
      from public.product_images pi
      where pi.product_id = p.id
      order by pi.is_primary desc, pi.sort_order asc
      limit 1
    ),
    (
      select count(*)
      from public.product_views pv
      where pv.product_id = p.id
    ),
    (
      select count(*)
      from public.offers o
      where o.product_id = p.id
    ),
    (
      select count(*)
      from public.chat_rooms cr
      where cr.product_id = p.id
        and cr.updated_at >= now() - interval '30 days'
    )
  from public.products p
  where p.owner_id = p_seller_id
  order by p.created_at desc
  limit 100;
end;
$function$;

