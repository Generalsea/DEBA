create or replace function private.delete_seller_listing(
  p_product_id uuid
)
returns boolean
language plpgsql
volatile
security definer
set search_path = public, private, pg_catalog
as $function$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception 'Authenticated seller is required' using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.profiles p
    where p.id = v_uid and p.account_type = 'seller'
  ) then
    raise exception 'Seller account is required' using errcode = '42501';
  end if;

  delete from public.products p
  where p.id = p_product_id
    and p.owner_id = v_uid
    and p.status = 'draft'
    and p.moderation_status in ('pending', 'rejected', 'needs_changes')
    and not exists (select 1 from public.orders o where o.product_id = p.id)
    and not exists (select 1 from public.offers o where o.product_id = p.id);

  return found;
end;
$function$;

