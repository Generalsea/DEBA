begin;

alter table public.products
  drop constraint if exists products_status_check;

alter table public.products
  add constraint products_status_check
  check (
    status = any (
      array[
        'draft'::text,
        'published'::text,
        'paused'::text,
        'reserved'::text,
        'sold'::text,
        'donated'::text,
        'archived'::text
      ]
    )
  );

create table if not exists public.product_views (
  id bigint generated by default as identity primary key,
  product_id uuid not null references public.products(id) on delete cascade,
  viewer_id uuid null references auth.users(id) on delete set null,
  visitor_key text not null,
  viewed_at timestamptz not null default now()
);

alter table public.product_views enable row level security;

revoke all on public.product_views from anon, authenticated;
grant all on public.product_views to service_role;

create index if not exists product_views_product_viewed_idx
  on public.product_views (product_id, viewed_at desc);

create index if not exists product_views_visitor_product_idx
  on public.product_views (visitor_key, product_id, viewed_at desc);

create or replace function private.record_product_view(
  p_product_id uuid,
  p_visitor_key text
)
returns boolean
language plpgsql
stable
security definer
set search_path = public, pg_catalog
as $function$
declare
  v_viewer_id uuid := auth.uid();
begin
  if p_product_id is null then
    return false;
  end if;

  if p_visitor_key is null
     or length(p_visitor_key) < 16
     or length(p_visitor_key) > 128
  then
    raise exception 'Invalid product visitor key';
  end if;

  if not exists (
    select 1
    from public.products p
    where p.id = p_product_id
      and p.status = 'published'
      and p.moderation_status = 'approved'
      and p.listing_type = 'sale'
  ) then
    return false;
  end if;

  if exists (
    select 1
    from public.product_views pv
    where pv.product_id = p_product_id
      and pv.visitor_key = p_visitor_key
      and pv.viewed_at > now() - interval '30 minutes'
  ) then
    return false;
  end if;

  insert into public.product_views (
    product_id,
    viewer_id,
    visitor_key,
    viewed_at
  )
  values (
    p_product_id,
    v_viewer_id,
    p_visitor_key,
    now()
  );

  return true;
end;
$function$;

