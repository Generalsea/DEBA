create or replace function private.update_seller_listing_status(
  p_product_id uuid,
  p_action text
)
returns public.products
language plpgsql
volatile
security definer
set search_path = public, private, pg_catalog
as $function$
declare
  v_uid uuid := auth.uid();
  v_product public.products%rowtype;
begin
  if v_uid is null then
    raise exception 'Authenticated seller is required' using errcode = '42501';
  end if;

  select p.* into v_product
  from public.products p
  where p.id = p_product_id
    and p.owner_id = v_uid
  for update;

  if not found then
    raise exception 'Listing not found or not owned by seller' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.profiles p
    where p.id = v_uid
      and p.account_type = 'seller'
  ) then
    raise exception 'Seller account is required' using errcode = '42501';
  end if;

  set local deba.lifecycle_override = '1';

  case p_action
    when 'submit_for_review' then
      if v_product.status <> 'draft' then
        raise exception 'Only draft listings can be submitted for review';
      end if;
      if v_product.moderation_status not in ('pending', 'rejected', 'needs_changes') then
        raise exception 'Listing is not eligible for review submission';
      end if;
      update public.products
      set status = 'draft', moderation_status = 'pending', updated_at = now()
      where id = v_product.id;

    when 'pause' then
      if v_product.status <> 'published' or v_product.moderation_status <> 'approved' then
        raise exception 'Only approved published listings can be paused';
      end if;
      update public.products
      set status = 'paused', updated_at = now()
      where id = v_product.id;

    when 'resume' then
      if v_product.status <> 'paused' or v_product.moderation_status <> 'approved' then
        raise exception 'Only approved paused listings can be resumed';
      end if;
      update public.products
      set status = 'published', published_at = coalesce(published_at, now()), updated_at = now()
      where id = v_product.id;

    when 'mark_sold' then
      if v_product.status not in ('published', 'paused') then
        raise exception 'Only published or paused listings can be marked sold';
      end if;
      update public.products
      set status = 'sold', sold_at = coalesce(sold_at, now()), updated_at = now()
      where id = v_product.id;

    when 'archive' then
      if v_product.status not in ('draft', 'paused', 'sold') then
        raise exception 'Only draft, paused, or sold listings can be archived';
      end if;
      update public.products
      set status = 'archived', updated_at = now()
      where id = v_product.id;

    when 'restore' then
      if v_product.status <> 'archived' then
        raise exception 'Only archived listings can be restored';
      end if;
      update public.products
      set status = 'draft', moderation_status = 'pending', sold_at = null, updated_at = now()
      where id = v_product.id;

    else
      raise exception 'Unknown seller listing action';
  end case;

  select p.* into v_product
  from public.products p
  where p.id = v_product.id;

  return v_product;
end;
$function$;

